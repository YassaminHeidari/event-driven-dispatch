#!/usr/bin/env python3
"""Turns k6 and pipeline results into a Markdown table.

Writes docs/benchmark.md and replaces the block between the BENCHMARK markers in README.md.
"""
import argparse
import datetime as dt
import json
import os
import platform
import re
import subprocess

START = "<!-- BENCHMARK:START -->"
END = "<!-- BENCHMARK:END -->"


def metric(summary, name, key):
    return summary["metrics"].get(name, {}).get(key)


def fmt(value, digits=1, suffix=""):
    if value is None:
        return "n/a"
    return f"{value:,.{digits}f}{suffix}"


def git_sha():
    try:
        return subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return os.environ.get("GITHUB_SHA", "unknown")[:7]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--k6", required=True)
    p.add_argument("--pipeline", required=True)
    p.add_argument("--workers", required=True)
    p.add_argument("--rate", required=True)
    p.add_argument("--duration", required=True)
    p.add_argument("--job-ms", required=True)
    p.add_argument("--k6-exit", default="0")
    a = p.parse_args()

    with open(a.k6) as f:
        k6 = json.load(f)
    with open(a.pipeline) as f:
        pipe = json.load(f)
    with open(a.workers) as f:
        workers = json.load(f)

    requests = metric(k6, "http_reqs", "count") or 0
    rps = metric(k6, "http_reqs", "rate")
    failed = metric(k6, "http_req_failed", "value")
    worker_threads = sum(int(w["state"].get("concurrency", 0)) for w in workers)
    when = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    machine = os.environ.get("BENCHMARK_MACHINE") or f"{os.cpu_count()} vCPU, {platform.system()}"

    rows = [
        ("HTTP throughput (POST /api/jobs)", fmt(rps, 1, " req/s")),
        ("HTTP latency p50", fmt(metric(k6, "http_req_duration", "med"), 2, " ms")),
        ("HTTP latency p95", fmt(metric(k6, "http_req_duration", "p(95)"), 2, " ms")),
        ("**HTTP latency p99**", "**" + fmt(metric(k6, "http_req_duration", "p(99)"), 2, " ms") + "**"),
        ("HTTP error rate", fmt((failed or 0) * 100, 2, " %")),
        ("End-to-end throughput (jobs completed)", fmt(pipe["completedPerSecond"], 1, " jobs/s")),
        ("End-to-end latency p50", fmt(pipe["endToEndP50Ms"], 1, " ms")),
        ("End-to-end latency p95", fmt(pipe["endToEndP95Ms"], 1, " ms")),
        ("**End-to-end latency p99**", "**" + fmt(pipe["endToEndP99Ms"], 1, " ms") + "**"),
        ("Jobs submitted / completed / failed", f"{int(requests):,} / {pipe['completed']:,} / {pipe['failed']:,}"),
    ]
    table = "| Metric | Result |\n|---|---|\n" + "\n".join(f"| {k} | {v} |" for k, v in rows)
    setup = (f"Target load: **{a.rate} jobs/s for {a.duration}** (k6 `constant-arrival-rate`), "
             f"each job sleeps {a.job_ms} ms. Stack: `docker compose` on a GitHub Actions runner "
             f"({machine}), 1 API instance, {len(workers)} workers × "
             f"{worker_threads // max(len(workers), 1)} consumer threads, 12 partitions. "
             f"Run: {when}, commit `{git_sha()}`.")
    note = ("End-to-end = from the moment the API accepted the job until a worker's COMPLETED "
            "status was stored in PostgreSQL (outbox → Kafka → worker → Kafka → API).")
    block = f"{START}\n{setup}\n\n{table}\n\n{note}\n{END}"

    os.makedirs("docs", exist_ok=True)
    with open("docs/benchmark.md", "w") as f:
        f.write("# Benchmark results\n\nGenerated by `scripts/benchmark.sh`. "
                "Re-run it with `docker compose up -d && ./scripts/benchmark.sh`.\n\n")
        f.write(block + "\n\n")
        f.write(f"k6 exit code: {a.k6_exit} (99 means a k6 threshold was crossed).\n\n")
        f.write("Raw data: `loadtest/results/k6-summary.json`, `loadtest/results/pipeline-stats.json`.\n")

    with open("README.md") as f:
        readme = f.read()
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
    if pattern.search(readme):
        readme = pattern.sub(lambda _: block, readme)
        with open("README.md", "w") as f:
            f.write(readme)

    print(block)


if __name__ == "__main__":
    main()
